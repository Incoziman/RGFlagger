"""Command line tool.

    python -m cameras list
    python -m cameras url camera1
    python -m cameras view            (all cameras in a grid, press q to quit)
    python -m cameras view camera1
    python -m cameras snapshot camera1 out.jpg
    python -m cameras info camera1    (codec: can browsers play it?)
    python -m cameras relay           (web relay for browsers / React)
"""

import argparse
import shutil
import subprocess
import sys

from . import _REPO_ROOT, get_url, list_cameras, open_camera, read_frame

RELAY_DIR = _REPO_ROOT / "relay"
MEDIAMTX_EXE = RELAY_DIR / "mediamtx" / "mediamtx.exe"
RELAY_CONFIG = RELAY_DIR / "mediamtx.yml"


def _info(name):
    import cv2

    cap = open_camera(name)
    try:
        fourcc = int(cap.get(cv2.CAP_PROP_FOURCC))
        codec = "".join(chr((fourcc >> 8 * i) & 0xFF) for i in range(4)).strip("\x00")
        width, height = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH)), int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
        fps = cap.get(cv2.CAP_PROP_FPS)
    finally:
        cap.release()
    print(f"{name}: codec={codec} {width}x{height} @ {fps:.0f} fps")
    if codec.lower() in ("h264", "avc1", "x264"):
        print("H.264: browsers can play this directly. Use: python -m cameras relay")
    else:
        print("Not H.264: browsers can't play this directly. Use: python -m cameras relay --transcode")


def _write_relay_config(transcode):
    """Write relay/mediamtx.yml (contains the password, ignored by git)."""
    lines = [
        "# Generated by `python -m cameras relay`. Contains the camera password: do not commit.",
        "authInternalUsers:",
        "  - user: any            # anyone may watch",
        "    pass:",
        "    ips: []",
        "    permissions:",
        "      - action: read",
        "  - user: any            # only this PC may publish / use the API",
        "    pass:",
        "    ips: ['127.0.0.1', '::1']",
        "    permissions:",
        "      - action: publish",
        "      - action: api",
        "paths:",
    ]
    for name in list_cameras():
        url = get_url(name)
        lines.append(f"  {name}:")
        if transcode:
            if not shutil.which("ffmpeg"):
                raise RuntimeError("--transcode needs ffmpeg on the PATH (winget install ffmpeg).")
            lines += [
                "    runOnDemand: >-",
                f"      ffmpeg -rtsp_transport tcp -i {url}",
                "      -c:v libx264 -preset veryfast -tune zerolatency -g 30 -an",
                f"      -f rtsp rtsp://127.0.0.1:8554/{name}",
                "    runOnDemandRestart: yes",
            ]
        else:
            lines += [
                f"    source: {url}",
                "    sourceOnDemand: yes",
                "    rtspTransport: tcp",
            ]
    RELAY_CONFIG.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _relay(transcode):
    if not MEDIAMTX_EXE.is_file():
        raise RuntimeError(
            f"MediaMTX not found at {MEDIAMTX_EXE}. Download the windows_amd64 zip from "
            "https://github.com/bluenviron/mediamtx/releases and unzip it there."
        )
    _write_relay_config(transcode)
    print("Relay running. In a browser / React app use:")
    for name in list_cameras():
        print(f"  http://<this-pc>:8889/{name}   (WebRTC, low delay)")
    print(f"  HLS alternative: http://<this-pc>:8888/<camera>/index.m3u8")
    print("Press Ctrl+C to stop.\n")
    try:
        subprocess.run([str(MEDIAMTX_EXE), str(RELAY_CONFIG)])
    except KeyboardInterrupt:
        pass


def _view(names):
    import cv2
    import numpy as np

    caps = {name: open_camera(name) for name in names}
    window = "cameras (press q to quit)"
    tile_w, tile_h = 640, 360
    cols = 1 if len(names) == 1 else 2
    try:
        while True:
            tiles = []
            for name, cap in caps.items():
                ok, frame = cap.read()
                if not ok:
                    frame = np.zeros((tile_h, tile_w, 3), dtype=np.uint8)
                    cv2.putText(frame, "no signal", (20, 60), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 0, 255), 2)
                frame = cv2.resize(frame, (tile_w, tile_h))
                cv2.putText(frame, name, (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 255, 0), 2)
                tiles.append(frame)
            while len(tiles) % cols:
                tiles.append(np.zeros_like(tiles[0]))
            rows = [np.hstack(tiles[i:i + cols]) for i in range(0, len(tiles), cols)]
            cv2.imshow(window, np.vstack(rows))
            if cv2.waitKey(1) & 0xFF == ord("q"):
                break
    finally:
        for cap in caps.values():
            cap.release()
        cv2.destroyAllWindows()


def main(argv=None):
    parser = argparse.ArgumentParser(prog="python -m cameras", description="Access the IP cameras.")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("list", help="print all camera names")
    p_url = sub.add_parser("url", help="print the RTSP URL of a camera")
    p_url.add_argument("name")
    p_view = sub.add_parser("view", help="show live video (all cameras if no name given)")
    p_view.add_argument("names", nargs="*")
    p_snap = sub.add_parser("snapshot", help="save one frame to an image file")
    p_snap.add_argument("name")
    p_snap.add_argument("output", nargs="?", default="snapshot.jpg")
    p_info = sub.add_parser("info", help="show codec/resolution (is it browser-compatible?)")
    p_info.add_argument("name")
    p_relay = sub.add_parser("relay", help="start the web relay (MediaMTX) for browsers / React")
    p_relay.add_argument("--transcode", action="store_true", help="convert to H.264 with ffmpeg")
    args = parser.parse_args(argv)

    try:
        if args.command == "list":
            print("\n".join(list_cameras()))
        elif args.command == "url":
            print(get_url(args.name))
        elif args.command == "view":
            _view(args.names or list_cameras())
        elif args.command == "snapshot":
            import cv2

            cv2.imwrite(args.output, read_frame(args.name))
            print(f"Saved {args.output}")
        elif args.command == "info":
            _info(args.name)
        elif args.command == "relay":
            _relay(args.transcode)
    except (KeyError, RuntimeError, ConnectionError) as e:
        print(f"Error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
